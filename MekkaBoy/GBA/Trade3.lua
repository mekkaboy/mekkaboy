-- places refused outright, by game family (group * 256 + map; a whole group as group * 256 - 1)
local function refusedMap(fam, group, map)
    if fam == "E" then
        if group == 25 then return true end                                           -- secret bases, link rooms, contests, the truck, the S.S. Tidal, the Pyramid
        if group == 26 then return not (map == 9 or map == 10 or (map >= 56 and map <= 59)) end   -- Safari Zone, Battle Frontier, Trainer Hill
        if group == 16 and (map <= 9 or map == 11) then return true end               -- the Pokemon League's rooms
        if group == 24 and map >= 104 and map <= 105 then return true end            -- Terra Cave
        if group == 24 and map >= 101 and map <= 103 then return true end            -- Marine Cave
    else
        if group == 0 then return true end                                            -- link rooms
        if group == 2 and map >= 1 and map <= 11 then return true end                -- Trainer Tower
        if group == 1 and ((map >= 63 and map <= 71) or (map >= 75 and map <= 80)) then return true end   -- Safari Zone, the Pokemon League's rooms
    end
    return false
end

