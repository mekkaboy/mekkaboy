-- ------------------------------------------------------------------ the game ---
local function rd8(a) return m.rd8(a) end
local function rd16(a) return m.rd8(a) + m.rd8(a + 1) * 256 end
local function rd32(a) return m.rd32(a) end
local function romSum(a, n) local h = 0 for i = 0, n - 1 do h = (h * 31 + m.rd8(a + i)) % 2147483647 end return h end
local function le4(v) return v % 256, floor(v / 256) % 256, floor(v / 65536) % 256, floor(v / 16777216) % 256 end
local function verify(p)
    local h = 0
    for _, name in ipairs(ROUTINES) do
        local s = romSum(p[name], 16)
        local a, b, c, d = le4(s)
        h = (((((h * 31 + a) % 2147483647) * 31 + b) % 2147483647 * 31 + c) % 2147483647 * 31 + d) % 2147483647
    end
    return h == p.sum
end
local function attach(machine)
    m, prof, code, profKey, hooked = machine, nil, nil, nil, {}
    if not (m and m.rd8 and m.blocks and m.runCPU and m.r) then return end
    local t = {}
    for i = 0, 3 do t[i + 1] = string.char(m.rd8(0x080000AC + i)) end
    code = table.concat(t)
    profKey = code .. m.rd8(0x080000BC)
    local p = GAMES[profKey]
    if p and verify(p) then prof = p end
    if prof then m.blocks[RET] = function() m._done = true m.stopAt = 0 return RET, 0 end end
end

-- call one of the game's routines and come back (short ones only: run here and now)
local function call(addr, a0, a1, a2, a3, s0, s1)
    local r = m.r
    local saved = {}
    for i = 0, 18 do saved[i] = r[i] end
    local key, halted, wait = m.key, m.halted, m.waitRAM
    r[0], r[1], r[2], r[3] = a0 or 0, a1 or 0, a2 or 0, a3 or 0
    if s0 then
        r[13] = r[13] - 32
        m.wr32(r[13], s0) m.wr32(r[13] + 4, s1 or 0)
    end
    r[14] = RET
    m.key = addr + 1
    m.halted, m.waitRAM, m._done = false, false, false
    local guard = 0
    while not m._done do
        m.runCPU(m.cyc + 400000)
        guard = guard + 1
        if guard > 400 then break end
    end
    local ret = r[0]
    for i = 0, 18 do r[i] = saved[i] end
    m.key, m.halted, m.waitRAM = key, halted, wait
    if not m._done then error("a routine of the game's did not come back") end
    return ret
end
-- a long one (the save): a little each tick, the game held still meanwhile
local function begin(addr, a0, done)
    local r = m.r
    local saved = {}
    for i = 0, 18 do saved[i] = r[i] end
    job = { saved = saved, key = m.key, halted = m.halted, wait = m.waitRAM, done = done, steps = 0 }
    r[0], r[1], r[2], r[3] = a0 or 0, 0, 0, 0
    r[14] = RET
    m.key = addr + 1
    m.halted, m.waitRAM, m._done = false, false, false
end
local function restore()
    local j = job
    job = nil
    local r = m.r
    local ret = r[0]
    for i = 0, 18 do r[i] = j.saved[i] end
    m.key, m.halted, m.waitRAM = j.key, j.halted, j.wait
    return j, ret
end
local function finish(ok)
    local j, ret = restore()
    j.done(ok and ret or nil)
end
-- the console calls this every tick while T.Holding() (GB/Console.lua)
function T.Tick(machine)
    if not job then return end
    if machine ~= m then job = nil return end
    local t0 = clockMs()
    -- (short steps: the save polls the flash chip, and the core's idle skip would make each poll a whole long step)
    repeat
        m.runCPU(m.cyc + 1232)
        job.steps = job.steps + 1
    until m._done or clockMs() - t0 > 6 or job.steps > 4000000
    if m._done then finish(true) elseif job.steps > 4000000 then finish(false) end
end

local function cb1() return rd32(prof.main) end
local function cb2() return rd32(prof.main + 4) end
local function sb1() return rd32(prof.sb1) end
local function trainerId() local a = rd32(prof.sb2) + 0xA return rd8(a) + rd8(a + 1) * 256 + rd8(a + 2) * 65536 + rd8(a + 3) * 16777216 end
local function flag(n) return call(prof.flagGet, n) ~= 0 end
local function settled() return m.halted or m.waitRAM end
local function place()
    local s = sb1()
    return rd8(s + 4), rd8(s + 5), rd16(s), rd16(s + 2)
end
local function dynamicWarps()
    local events = rd32(prof.header + 4)
    if events < 0x08000000 then return false end
    local n, warps = rd8(events + 1), rd32(events + 8)
    for i = 0, n - 1 do if rd8(warps + i * 8 + 7) == 0x7F then return true end end
    return false
end

-- may a trade start now? (all read from memory, except the Safari Zone flag)
local function canStart(kind)
    if not m then return false, "Start your game first." end
    if not prof then
        if FAMILY[code or ""] then return false, ("Trading where you stand works with Pokemon Emerald, FireRed 1.0 and LeafGreen 1.1. This copy (%s revision %d) isn't one MekkaBoy has checked yet: trade at a Pokemon Center instead."):format(NAMES[code], m.rd8(0x080000BC)) end
        return false, "Trading where you stand works in Pokemon Emerald, FireRed and LeafGreen."
    end
    if job or dt then return false, "A trade or battle is already being set up." end
    if cb2() ~= prof.cb2 + 1 or cb1() ~= prof.cb1 + 1 then return false, "Stand on the map, out of any menu or battle, first." end
    if rd8(prof.locked) ~= 0 or rd8(prof.scriptStatus) ~= 2 then return false, "Close any menu and finish what's happening in the game first." end
    if rd8(prof.fade + 7) >= 128 then return false, "Wait for the screen to settle." end
    if prof.questLog and (rd8(prof.questLog) == 2 or rd8(prof.questLog) == 3) then return false, "Let the game finish its \"Previously on your quest\" first." end
    if rd8(prof.received) ~= 0 or rd8(prof.wireless) ~= 0 then return false, "The game is already using the link." end
    if rd8(prof.differentFile) ~= 0 then return false, "Save your game once from its own menu first." end
    local av = rd8(prof.avatar)
    if av % 32 >= 2 then return false, (av % 32 >= 8) and "Get out of the water first." or "Get off your bike first." end
    if kind == "battle" then
        if rd8(prof.party) < 1 then return false, "You need a Pokemon to battle." end
    elseif rd8(prof.party) < 2 then return false, "You need at least two Pokemon to trade." end
    local group, map = place()
    if not MAP_KINDS[rd8(prof.header + 0x17)] or refusedMap(FAMILY[code], group, map) or dynamicWarps() then
        return false, "Not here: a trade's save could leave you stuck in this place. Step outside or into an ordinary building."
    end
    if not settled() then return false, "again" end
    if flag(FLAGS[code].safari) then return false, "Not in the Safari Zone." end
    return true
end

local function info()
    return hex8(trainerId()) .. code .. tostring(m.rd8(0x080000BC) % 10) .. (flag(FLAGS[code].story) and "1" or "0")
end
local function parseInfo(s)
    local tid, c, rev, story, k = (s or ""):match("^(%x%x%x%x%x%x%x%x)(%u%u%u%u)(%d)([01])(%l?)")
    if not tid then return nil end
    return { tid = tonumber(tid, 16), code = c, rev = tonumber(rev), story = story == "1", kind = (k == "b") and "battle" or "trade" }
end
local WORDS = { trade = { noun = "trade", screen = "trade screen", done = "Trade done" },
                battle = { noun = "battle", screen = "battle", done = "Battle over" } }

-- ------------------------------------------------- trading where you stand ---
local function tell(text) local g = wireOf() if g then g:tx("T", text:sub(2)) end end      -- (text: "T?...", the stand-in adds the kind)
local function say(text) Print(text) if MB.Note then MB.Note(text:sub(1, 60)) end end
local function abort(why, quiet)
    local was = dt
    dt = nil
    if job then restore() end      -- (a save cut short: the save it was writing is not signed, so the last one stands)
    if was and not quiet then say(why) end
    if MB.Friends and MB.Friends.HideAsk then MB.Friends.HideAsk("trade") end
end
-- the ordinary save first, the game held still from then until the trade screen (or until it is called off)
local function saveThen(fn)
    begin(prof.save, 0, function(status)
        if status ~= 1 then abort(status and "The game couldn't save, so the trade was not started." or "The game's save didn't finish, so the trade was not started.") return end
        if dt then fn() end
    end)
end
-- the game's own rule between Emerald and FireRed/LeafGreen
local function ruleBreak(a, b)
    if FAMILY[a.code] == FAMILY[b.code] then return nil end
    local e, k = (FAMILY[a.code] == "E") and a or b, (FAMILY[a.code] == "E") and b or a
    if e.story and k.story then return nil end
    return "Emerald and FireRed/LeafGreen can trade once the Emerald player is Champion and the FireRed/LeafGreen player has finished the Sevii Islands story (the games' own rule)."
end
local function hostDecides()
    local s = session()
    if not (dt and dt.mine and dt.theirs and s and s.host) then return end
    local bad = dt.kind == "trade" and ruleBreak(dt.mine, dt.theirs)
    if bad then tell("T-" .. bad) abort(bad) return end
    dt.stage, dt.at = "go", now()
    tell("TG")
end
-- straight to the trade screen (the game was saved just before and has been held since)
local function start()
    local s, g = session(), wireOf()
    if not (dt and s and g) then return end
    local host = s.host
    local group, map, x, y = place()
    dt.home = { group, map, x, y }
    call(prof.warp, 0, group, map, 0xFFFFFFFF, x, y)                 -- the trade's own save carries on from here
    m.wr8(prof.savedCount, 2)
    if prof.savedPlayers then                                          -- (Emerald checks the two it meets are these, in link order)
        local mine, theirs = dt.mine.tid, dt.theirs.tid
        m.wr32(prof.savedPlayers + 4, host and mine or theirs)
        m.wr32(prof.savedPlayers + 0x1C + 4, host and theirs or mine)
    end
    dt.slot = host and 0 or 1
    if dt.kind == "battle" then
        -- what the Colosseum would have done: a seat for each player (the battler each one is), a single battle, the
        -- party kept as it is and healed for the battle only (it comes back exactly as it was, so this is no free
        -- Pokemon Center), the bag kept (the battle hands it back from this copy), the battle's music
        m.wr8(prof.localId, dt.slot)
        call(prof.seat, dt.slot)
        m.wr8(prof.fieldCount, 2)
        m.wr16(prof.var8004, 1)                                        -- a single battle
        m.wr16(prof.linkType, 0x2211)                                  -- a link battle
        call(prof.lock)
        call(prof.keepParty)
        call(prof.heal)
        call(prof.keepBag)
        call(prof.battleMusic, FAMILY[code] == "E" and 476 or 266)
        m.wr32(prof.battleType, 0x0A)                                  -- link, trainer
        call(prof.clearField)
        m.wr16(prof.opponent, 0x800)                                   -- the other player
        m.wr32(prof.main, 0)
        m.wr32(prof.main + 8, prof.battleEnd + 1)                      -- where the battle goes when it is over
        call(prof.setcb2, prof.battle + 1)
    else
        m.wr8(prof.picked, 0) m.wr8(prof.picked + 1, 0)
        call(prof.lock)
        call(prof.quiet)
        m.wr32(prof.main, 0)
        call(prof.setcb2, prof.tradeMenu + 1)
    end
    g.closedAt = g.frame                                               -- (so the stand-in holds whichever game opens the link first)
    dt.stage, dt.at = "trading", now()
end

-- ask the linked partner (name: optional, who you mean)
function T.Request(name, tries, kind)
    kind = kind or "trade"
    local W = WORDS[kind]
    local s = session()
    if not (s and s.state == "linked") then
        if not name or name == "" then Print("Link with someone first (/mb link, or the MekkaBoy mark on their portrait), then /mb " .. kind .. ".") return end
        if not m or not prof then local _, why = canStart(kind) Print(why) return end
        pending = { name = name, at = now(), kind = kind }
        Print(("Asking %s to link. The %s request follows once you're linked."):format(short(name), W.noun))
        if MB.Friends and MB.Friends.Call then MB.Friends.Call(name) end
        return
    end
    if name and name ~= "" and not MB.Link.NameIs(s.partner, name) then Print(("You're linked with %s. /mb link off first to %s someone else."):format(short(s.partner), kind == "battle" and "battle" or "trade with")) return end
    if not wireOf() then Print("This needs Pokemon Emerald, FireRed or LeafGreen in both consoles.") return end
    local ok, why = canStart(kind)
    if not ok then
        if why == "again" then
            if (tries or 0) < 30 then T.retry = { at = now(), fn = function() T.Request(name, (tries or 0) + 1, kind) end } else Print("The game was too busy to start: try again.") end
            return
        end
        Print(why) return
    end
    dt = { role = "ask", stage = "saving", partner = s.partner, at = now(), kind = kind }
    say(("Saving your game, then asking %s to %s here..."):format(short(s.partner), kind))
    saveThen(function()
        dt.mine = parseInfo(info())
        dt.stage, dt.at = "asking", now()
        tell("T?" .. T.InfoText() .. (kind == "battle" and "b" or "t"))
    end)
end
function T.InfoText() return hex8(dt.mine.tid) .. dt.mine.code .. dt.mine.rev .. (dt.mine.story and "1" or "0") end
function T.Cancel()
    if not dt then Print("No trade or battle is being set up.") return end
    if dt.stage == "trading" then Print(("The %s is open: leave it in the game."):format(WORDS[dt.kind].screen)) return end
    tell("TX")
    abort(dt.kind == "battle" and "Battle called off." or "Trade called off.")
end

local function answer(yes)
    if MB.Friends and MB.Friends.HideAsk then MB.Friends.HideAsk("trade") end
    local ask = T.asked
    T.asked = nil
    if not ask then return end
    local s = session()
    if not (s and s.state == "linked") then return end
    if not yes then tell("T-" .. "said not now") return end
    local kind = ask.theirs.kind
    local ok, why = canStart(kind)
    if not ok then
        if why == "again" then ok, why = false, "Your game was busy just then: try again." end
        tell("T-" .. why) Print(why) return
    end
    dt = { role = "answer", stage = "saving", partner = s.partner, at = now(), theirs = ask.theirs, kind = kind }
    say("Saving your game for the " .. kind .. "...")
    saveThen(function()
        dt.mine = parseInfo(info())
        dt.stage, dt.at = "ready", now()
        tell("T+" .. T.InfoText())
        hostDecides()
    end)
end
T.Answer = answer

-- a message about a trade, from the linked partner (GBA/Cable.lua)
function T.Control(ghost, text)
    local what, rest = text:sub(1, 1), text:sub(2)
    local s = session()
    if not s then return end
    if what == "?" then
        if dt or job then tell("T-is setting up another trade or battle") return end
        tell("T~")
        local theirs = parseInfo(rest)
        if not theirs then tell("T-couldn't read the request") return end
        if not prof then local _, why = canStart(theirs.kind) tell("T-" .. (why or "can't here")) Print(("%s asked to %s where you stand, but: %s"):format(short(s.partner), theirs.kind, why)) return end
        T.asked = { theirs = theirs, at = now() }
        local text2
        if theirs.kind == "battle" then
            text2 = ("|cffffd100%s|r wants to battle right where you both are (%s).\nYour Pokemon are healed for the battle and come back exactly as they were. Your game saves before the battle and again after it."):format(short(s.partner), NAMES[theirs.code] or theirs.code)
        else
            text2 = ("|cffffd100%s|r wants to trade Pokemon right where you both are (%s).\nYour game is saved first, then the trade screen opens."):format(short(s.partner), NAMES[theirs.code] or theirs.code)
        end
        if MB.Friends and MB.Friends.Ask then
            MB.Friends.Ask("trade", text2, theirs.kind == "battle" and "Battle" or "Trade", "Not now", function() answer(true) end, function() answer(false) end, 60)
        else
            Print(text2:gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", "") .. " /mb " .. theirs.kind .. " yes or no")
        end
    elseif what == "~" then
        if dt then dt.heard = true end
    elseif what == "+" then
        if not (dt and dt.role == "ask" and dt.stage == "asking") then return end
        dt.theirs = parseInfo(rest)
        if not dt.theirs then abort("The trade answer couldn't be read.") return end
        dt.stage, dt.at = "ready", now()
        say(("%s said yes. Opening the %s..."):format(short(s.partner), WORDS[dt.kind].screen))
        hostDecides()
    elseif what == "-" then
        if T.asked then T.asked = nil if MB.Friends and MB.Friends.HideAsk then MB.Friends.HideAsk("trade") end end
        if dt and dt.stage ~= "trading" then abort(("%s can't %s now: %s."):format(short(s.partner), dt.kind, rest ~= "" and rest or "no reason given")) end
    elseif what == "X" then
        if T.asked then local k = T.asked.theirs.kind T.asked = nil if MB.Friends and MB.Friends.HideAsk then MB.Friends.HideAsk("trade") end Print(short(s.partner) .. " called the " .. k .. " off.") end
        if dt and dt.stage ~= "trading" then abort(short(s.partner) .. " called the " .. dt.kind .. " off.") end
    elseif what == "G" then
        if not (dt and dt.stage == "ready" and not s.host) then tell("TX") return end
        local bad = dt.kind == "trade" and dt.theirs and dt.mine and ruleBreak(dt.mine, dt.theirs)
        if bad then tell("T-" .. bad) abort(bad) return end
        start()
        tell("TS")
    elseif what == "S" then
        if dt and dt.stage == "go" and s.host then start() end
    end
end

-- once a link is up, a trade asked for before it follows (GB/Link.lua)
function T.Linked(partner)
    if pending and MB.Link.NameIs(pending.name, partner) and now() - pending.at < 120 then
        local kind = pending.kind
        pending = nil
        T.after = { at = now() + 1.5, fn = function() T.Request(partner, nil, kind) end }
    end
end

-- ------------------------------------------------------------ a trade's save ---
local function tradeId()
    local s = session()
    local g = s and s.ghost
    if not (s and g and prof) then return nil end
    -- (the two trainers as the trade's link met them: the same on both sides)
    local a, b = rd32(prof.linkPlayers + 4), rd32(prof.linkPlayers + 0x1C + 4)
    return ("%s.%d.%d"):format(hex8(math.min(a, b)) .. hex8(math.max(a, b)), s.id or 0, g.round or 0), g.round or 0
end
-- the trade's own save begins: keep the save from just before it (GBA/Core.lua getSave copies the flash as text)
local function saveBegins()
    if cb2() ~= prof.saveEnd + 1 then return end
    local s = session()
    if not s then return end
    local id, round = tradeId()
    if not id then return end
    local before = m.getSave()
    local store = MB.CurrentStore and MB.CurrentStore() or nil
    journal()[id] = { id = id, partner = s.partner, state = "saving", round = round, store = store, game = NAMES[code],
                      at = date and date("%Y-%m-%d %H:%M") or "?", before = before }
    T.live = id
    T.watched = (T.watched or 0) + 1
end
local function saveSigned()
    if cb2() ~= prof.saveEnd + 1 then return end
    local e = T.live and journal()[T.live]
    if e and e.state == "saving" then e.state = "signed" T.signed = (T.signed or 0) + 1 end
end
local function hook(addr, fn)
    local key = addr + 1
    local blocks = m.blocks
    local cur = blocks[key]
    if cur and cur == hooked[key] then return end
    local orig = cur or m.compile(key)
    local w = function() pcall(fn) return orig() end
    blocks[key] = w
    hooked[key] = w
end

-- a battle where you stand is over: the other player's name and trainer number on their card, as the Colosseum's
-- card swap would have left them, so the game's battle record names them (it writes it next)
local function battleEnds()
    if not (dt and dt.kind == "battle" and dt.slot and not dt.carded) then return end
    dt.carded = true
    local p = 1 - dt.slot
    local lp = prof.linkPlayers + p * 0x1C
    local tc = prof.cards + p * (FAMILY[code] == "E" and 0x64 or 0x60)
    for i = 0, 7 do m.wr8(tc + 0x30 + i, rd8(lp + 8 + i)) end
    m.wr16(tc + 0x0E, rd16(lp + 4))
end

-- after a trade, or a link that ended: what each saved entry means now
local function settleLive(ended)
    local id = T.live
    if not id then return end
    local e = journal()[id]
    if not e then T.live = nil return end
    if not ended then
        local g = session() and session().ghost
        if not (g and g.round and g.round > e.round) then return end
        -- the link closed in the ordinary way after the save: both games went past signing
        if e.state == "signed" or e.state == "saving" then journal()[id] = nil end
        T.live = nil
        return
    end
    T.live = nil
    if e.state == "signed" then
        e.state, e.endedAt = "unconfirmed", time and time() or 0
        Print(("|cffffd100The link with %s ended just as your games were saving the trade.|r Your game kept the trade. %s's may not have: MekkaBoy will check with %s's MekkaBoy and, if theirs didn't keep it, offer to undo it on your side. /mb trades lists it."):format(short(e.partner), short(e.partner), short(e.partner)))
        T.Check(e, true)
    elseif e.state == "saving" then
        e.state, e.before, e.endedAt = "unsigned", nil, time and time() or 0
        Print(("|cffffd100The link with %s ended while your games were saving the trade.|r Your game did not keep it: /mb reset brings you back to just before the trade. If %s's game did keep it, their MekkaBoy will offer to undo it."):format(short(e.partner), short(e.partner)))
    end
end

-- the link ended (GB/Link.lua)
function T.LinkEnded()
    if T.asked then T.asked = nil if MB.Friends and MB.Friends.HideAsk then MB.Friends.HideAsk("trade") end end
    if dt and dt.stage ~= "trading" then abort("The link ended, so the " .. dt.kind .. " was called off.")
    elseif dt then
        if dt.stage == "trading" and (dt.kind == "battle" or not T.live) then
            Print(("The link ended during the %s. /mb reset restarts your game from its save from just before it (nothing is lost)."):format(dt.kind))
        end
        dt = nil
    end
    settleLive(true)
end

-- compare notes with the partner of a trade that may not have been kept on both sides
function T.Check(e, force)
    if not e or e.state ~= "unconfirmed" then return end
    local t = now()
    if not force and seenAsk[e.id] and t - seenAsk[e.id] < 60 then return end
    seenAsk[e.id] = t
    MB.Link.Send("J?00" .. e.id, "WHISPER", e.partner, LANE)
end
-- a MekkaBoy we know answered something (Friends.lua): ask about any trade with them still unsettled
function T.Seen(sender)
    for _, e in pairs(journal()) do
        if e.state == "unconfirmed" and MB.Link.NameIs(e.partner, sender) then T.Check(e) end
    end
end
local function list()
    local out = {}
    for _, e in pairs(journal()) do if e.state == "unconfirmed" then out[#out + 1] = e end end
    table.sort(out, function(a, b) return (a.at or "") < (b.at or "") end)
    return out
end
T.Unsettled = list

local function offerUndo(e)
    local text = ("|cffffd100%s's game didn't keep your trade|r (the link dropped while saving). Yours did, so a Pokemon is now on both sides and one on neither.\nUndo it on your side? Your %s save goes back to just before the trade (anything you did after it is lost)."):format(short(e.partner), e.game or "game")
    if MB.Friends and MB.Friends.Ask then
        MB.Friends.Ask("undo", text, "Undo trade", "Keep", function() T.Undo(e.id) end, function()
            Print("Kept. /mb trades undo still undoes it later, while MekkaBoy has the save from before it.")
        end, 0)
    end
    Print(text:gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", "") .. " /mb trades undo")
end

-- J?/J! (GB/Link.lua routes kind "J" here)
function T.Heard(text, channel, sender)
    if MB.Link.IsMe(sender) then return end
    local what, rest = text:sub(2, 2), text:sub(5)
    if what == "?" then
        local e = journal()[rest]
        local said = "unknown"
        if e then said = (e.state == "unsigned") and "no" or "yes" end
        MB.Link.Send("J!00" .. rest .. ";" .. said, "WHISPER", sender, LANE)
    elseif what == "!" then
        local id, said = rest:match("^([^;]+);(%a+)$")
        local e = id and journal()[id]
        if not (e and e.state == "unconfirmed" and MB.Link.NameIs(e.partner, sender)) then return end
        if said == "yes" then
            journal()[id] = nil
            Print(("Your trade with %s is confirmed: both games kept it."):format(short(e.partner)))
        elseif said == "no" then
            offerUndo(e)
        elseif not e.toldUnknown then
            e.toldUnknown = true
            Print(("%s's MekkaBoy has no note of your trade (their game client may have closed before it could write one). If their game still has the Pokemon they traded you, /mb trades undo puts your save back to just before the trade."):format(short(e.partner)))
        end
    end
end

function T.Undo(id)
    local e = id and journal()[id]
    if not e then local l = list() e = l[#l] end
    if not e or not e.before then Print("There is no trade MekkaBoy can undo.") return end
    local s = session()
    if s and s.state == "linked" then Print("End the link first (/mb link off).") return end
    if not (MB.RestoreBattery and MB.RestoreBattery(e.store, e.before)) then
        Print(("Put %s in the console and start it, then /mb trades undo."):format(e.game or "the game"))
        return
    end
    journal()[e.id] = nil
    Print(("Undone: your %s save is back to just before the trade with %s, and the game restarted from it."):format(e.game or "game", short(e.partner)))
end

-- ---------------------------------------------------------- every frame ---
-- after each emulated frame (GB/Console.lua)
function T.Frame(machine)
    if machine ~= m then attach(machine) end
    if not prof then return end
    hook(prof.saveBegin, saveBegins)
    hook(prof.battleEnd, battleEnds)
    hook(prof.saveSign, saveSigned)
    if T.live then settleLive(false) end
    if dt and dt.stage == "trading" then
        local c = cb2()
        if c == prof.linkedField + 1 then
            -- the trade screen is done and wants the link rooms: the ordinary way back to the map instead, where we were
            for _ = 1, 90 do if settled() then break end m.runFrame(false) end
            m.wr32(prof.main, prof.cb1 + 1)
            m.wr32(prof.fcb, 0) m.wr32(prof.fcb2, 0)
            call(prof.scripts)
            call(prof.unlock)
            call(prof.setcb2, prof.field + 1)
            dt.stage = "back"
        elseif c == prof.linkError + 1 or c == prof.linkError2 + 1 then
            local k = dt.kind
            dt = { kind = k }
            Print(("The link broke during the %s. /mb reset restarts your game from its save (it was saved just before the %s)."):format(dt.kind, dt.kind))
            dt = nil
        end
    elseif dt and dt.stage == "back" then
        if cb2() == prof.cb2 + 1 and rd8(prof.locked) == 0 then
            local k = dt.kind
            dt = nil
            say(WORDS[k].done .. ". You're back where you were.")
        end
    end
end

-- something went wrong in here: drop the trade being set up, never the game
function T.Fail()
    if job then pcall(restore) end
    job, dt = nil, nil
end

-- should the game be held still (not run) this tick? (GB/Console.lua)
function T.Holding()
    if job then return true end
    return dt ~= nil and (dt.stage == "saving" or dt.stage == "asking" or dt.stage == "ready" or dt.stage == "go")
end
function T.Busy() return job ~= nil or dt ~= nil end

-- timeouts and the things that wait a moment (a tick of their own, so they run while the game is held or paused)
local clock = CreateFrame("Frame")
local LIMITS = { asking = 75, ready = 30, go = 20 }
clock:SetScript("OnUpdate", function()
    local t = now()
    if T.retry and t - T.retry.at > 0.2 then
        local r = T.retry T.retry = nil
        r.fn()
    end
    if T.after and t >= T.after.at then local a = T.after T.after = nil a.fn() end
    if dt and LIMITS[dt.stage] and t - dt.at > LIMITS[dt.stage] then
        local s = session()
        local who = s and short(s.partner) or "Your partner"
        if dt.stage == "asking" and not dt.heard then
            tell("TX") abort(who .. "'s MekkaBoy didn't answer the trade request (it may be older than yours: both need 0.20.3 or later).")
        elseif dt.stage == "asking" then
            tell("TX") abort(who .. " didn't answer the trade request.")
        else
            tell("TX") abort("The trade took too long to start, so it was called off.")
        end
    end
    if T.asked and t - T.asked.at > 62 then answer(false) end
    if pending and t - pending.at > 120 then pending = nil end
end)
-- trades still unsettled after logging in: ask their partners once things have settled
local later = CreateFrame("Frame")
local loginAt = now()
later:SetScript("OnUpdate", function(f)
    if now() - loginAt < 20 then return end
    f:SetScript("OnUpdate", nil)
    for id, e in pairs(journal()) do
        if e.state == "saving" or e.state == "signed" then
            -- (the game client closed in the middle of a trade's save)
            T.live = id
            settleLive(true)
        end
    end
    for _, e in ipairs(list()) do T.Check(e) end
end)

-- ------------------------------------------------------------- commands ---
MB.AddCommand("trade", "trade [name] - trade Pokemon right where you stand (Emerald, FireRed, LeafGreen), with the player you're linked with; trade off calls it off", function(rest)
    rest = (rest or ""):gsub("^%s+", ""):gsub("%s+$", "")
    local word = rest:lower()
    if word == "off" or word == "cancel" then T.Cancel() return end
    if word == "yes" then answer(true) return end
    if word == "no" then answer(false) return end
    T.Request(rest ~= "" and rest or nil)
end)
MB.AddCommand("battle", "battle [name] - a link battle right where you stand (Emerald, FireRed, LeafGreen), with the player you're linked with; battle off calls it off", function(rest)
    rest = (rest or ""):gsub("^%s+", ""):gsub("%s+$", "")
    local word = rest:lower()
    if word == "off" or word == "cancel" then T.Cancel() return end
    if word == "yes" then answer(true) return end
    if word == "no" then answer(false) return end
    T.Request(rest ~= "" and rest or nil, nil, "battle")
end)
MB.AddCommand("trades", "trades - Gen 3 trades whose save may not have been kept on both sides; trades check | undo | keep", function(rest)
    local word = (rest or ""):lower():gsub("^%s+", ""):gsub("%s+$", "")
    local l = list()
    if word == "undo" then T.Undo(l[#l] and l[#l].id) return end
    if word == "keep" then
        local e = l[#l]
        if not e then Print("Nothing to keep.") return end
        journal()[e.id] = nil
        Print(("Kept your trade with %s as it is."):format(short(e.partner)))
        return
    end
    if #l == 0 then Print("No trades waiting to be checked. Every Gen 3 trade over MekkaBoy is checked on both sides as it saves.") return end
    for _, e in ipairs(l) do
        Print(("%s, %s with %s: your game kept it; not yet known whether %s's did."):format(e.at or "?", e.game or "a game", short(e.partner), short(e.partner)))
        if word == "check" then T.Check(e, true) end
    end
    if word ~= "check" then Print("/mb trades check asks again; /mb trades undo puts your save back to just before the trade; /mb trades keep forgets it.") end
end)

