-- Gen 3 trades and battles (Pokemon Emerald, FireRed 1.0, LeafGreen 1.1): trading or battling right where you stand,
-- and keeping a trade safe when the link drops while the two games save it.
--
-- BATTLING WHERE YOU STAND (/mb battle) goes the same way as a trade, then does what the Colosseum's chairs and
-- attendant would have: a seat for each player, a single link battle, the party and the bag kept as they are (the
-- party healed for the battle only, so it comes back exactly as it went in: no free heal), and after it the other
-- trainer's name and number on their card, so the game's own battle record names them. The game saves on its own
-- after a link battle, as at the Colosseum; nothing changes hands, so a battle has no save to watch.
--
-- TRADING WHERE YOU STAND. Two linked players (/mb link) can trade without walking to a Pokemon Center: /mb trade,
-- or A while facing a friend's trainer in Together. Each game is first saved the ordinary way (as the attendant does
-- before every link) and held still; the other player is asked; then both games are switched straight to the game's
-- own trade screen, which opens the link itself. When the trade screen is done it asks for the link rooms' linked
-- overworld; that is swapped for the ordinary way back to the map (the one closing the party menu takes), so each
-- trainer is back on their own square, free to walk. Everything that decides a trade is still the game's own: the
-- lists, what may be traded, the animation, the save. MekkaBoy checks first what the attendant would have checked
-- (a quiet moment on the map, two or more Pokemon, a game saved before) and refuses places a trade's save could
-- strand you (elevators, secret bases, the Safari Zone, the Battle Frontier, link rooms, the water). Between Emerald
-- and FireRed/LeafGreen it applies the games' own rule (only checked at the Pokemon Center's desk): the Emerald
-- player must be Champion and the FireRed/LeafGreen player must have finished the Sevii Islands story.
--
-- A TRADE'S SAVE. Both games save a trade, then each "signs" its save when it hears the other is ready; a save only
-- counts once signed. Over chat the two signatures are a moment apart, so if one player's game stops in that moment,
-- one save can hold the trade and the other not: one Pokemon on both sides, the other on neither. That cannot be
-- made impossible over a chat line, so it is noticed and put right with the player's say-so: each game's save from
-- just before the trade is kept until both are known to have signed. If the link ends first, the player is told,
-- and the two MekkaBoys compare notes as soon as they meet again ("did yours keep it?"). If one game kept the trade
-- and the other did not, the one that kept it is offered to undo it (its save goes back to just before the trade),
-- so both are as they were. Nothing is changed without the player pressing Undo. This covers every Gen 3 trade over
-- MekkaBoy, at a Pokemon Center or where you stand.
--
-- Messages on the link itself (the stand-in's wire, GBA/Cable.lua, kind "T"):
--   T?<info>  "trade here?"     T~  "heard you"     T+<info>  "yes"     T-<words>  "no, or can't"
--   TG        "go" (from the player whose console leads the link)     TS  "started"     TX  "called off"
--   info: <trainer id, 8 hex digits><game code, 4><revision, 1 digit><finished the story: 0 or 1>
-- Messages between the two MekkaBoys after a link (whispered, lane 5, kind "J"):
--   J?00<trade>                      "did your game keep our trade?"
--   J!00<trade>;<yes|no|unknown>
